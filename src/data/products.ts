export const getProductById = (id: string): Product | undefined => {
  return products.find(p => p.id === id);
};

export const getProductsByCategory = (category: string): Product[] => {
  if (category.toLowerCase() === 'all') return products;
  return products.filter(p => p.category.toLowerCase() === category.toLowerCase());
};

export const searchProducts = (query: string): Product[] => {
  const searchTerm = query.toLowerCase();
  return products.filter(
    p => p.name.toLowerCase().includes(searchTerm) || p.category.toLowerCase().includes(searchTerm)
  );
};

export const getTrendingProducts = (): Product[] => {
  return products.filter(p => p.badge === 'hot' || (p.rating && p.rating >= 4.7)).slice(0, 8);
};

export const getBestSellers = (): Product[] => {
  return products.filter(p => p.reviewCount && p.reviewCount >= 80).slice(0, 8);
};

export const getNewArrivals = (): Product[] => {
  return products.filter(p => p.badge === 'new').slice(0, 8);
};

export const getOnSaleProducts = (): Product[] => {
  return products.filter(p => p.discount && p.discount > 0).slice(0, 8);
};
